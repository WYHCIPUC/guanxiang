export const lunarMansions = mansionNames.map(([name, quadrant, animal, theme], index) => ({ index, name, quadrant, animal, theme }))

export function getStarOfficer(dateValue) {
  const [year, month, day] = dateValue.split('-').map(Number)
  const dayNumber = Math.floor(Date.UTC(year, month - 1, day, 12) / 86400000)
  return { ...lunarMansions[((dayNumber % 28) + 28) % 28], mode: 'productized-cycle' }
}
